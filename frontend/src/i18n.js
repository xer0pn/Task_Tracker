export function t(key) {
  return messages[language.value][key] ?? messages.en[key] ?? key;
}
export function statusLabel(status) {
  return t(
    { Todo: "statusTodo", InProgress: "statusInProgress", Done: "statusDone" }[
      status
    ] ?? status,
  );
}
export function priorityLabel(priority) {
  return t(priority.toLowerCase());
}
export function setLanguage(next) {
  language.value = next;
  window.localStorage.setItem("task-tracker-language", next);
}
export function toggleLanguage() {
  setLanguage(language.value === "en" ? "ar" : "en");
}
